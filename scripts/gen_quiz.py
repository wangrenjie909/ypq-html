questions = []

# 类型A：效力哪队（每个球星的每个球队生成一题，共约30题）
for name, (teams, nums) in players.items():
    for t in teams:
        wrong = random.sample([x for x in team_pool if x != t], 3)
        opts = [t] + wrong
        random.shuffle(opts)
        questions.append({"q": f"{name}效力过哪支球队？", "opts": opts, "ans": opts.index(t)})

# 类型B：号码几号（每个球星的每个号码生成一题）
for name, (teams, nums) in players.items():
    for n in nums:
        wrong = random.sample([x for x in num_pool if x != n], 3)
        opts = [str(n)] + [str(x) for x in wrong]
        random.shuffle(opts)
        questions.append({"q": f"{name}的球衣号码是几号？", "opts": opts, "ans": opts.index(str(n))})

# 类型C：是否效力过（真/假题）
for name, (teams, nums) in players.items():
    for t in teams:
        questions.append({"q": f"{name}效力过{t}吗？", "opts": ["是", "否"], "ans": 0})
    # 每个球星加4个假的（随机非效力队）
    fake_teams = random.sample([x for x in team_pool if x not in teams], min(6, len([x for x in team_pool if x not in teams])))
    for ft in fake_teams:
        questions.append({"q": f"{name}效力过{ft}吗？", "opts": ["是", "否"], "ans": 1})

random.shuffle(questions)

# 输出 JS 数组
lines = []
for q in questions[:1000]:
    opts_js = ", ".join('"' + o + '"' for o in q["opts"])
    lines.append(f'        {{ q: "{q["q"]}", opts: [{opts_js}], ans: {q["ans"]} }},')

js = "\n".join(lines)
open("quiz200.txt", "w", encoding="utf-8").write(js)
